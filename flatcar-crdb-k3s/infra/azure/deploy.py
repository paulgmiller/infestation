#!/usr/bin/env python3
"""Prepare, apply, and bootstrap a pinned Azure plan with one command."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import secrets
import re
import shutil
import subprocess
import sys

PROJECT = Path(__file__).resolve().parent
SOURCE = PROJECT.parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--plan-dir', type=Path, required=True)
    parser.add_argument('--stack', required=True)
    parser.add_argument('--ssh-private-key', type=Path, required=True)
    parser.add_argument('--flatcar-version', required=True)
    parser.add_argument('--cilium', default='cilium')
    parser.add_argument('--initialize-new-cluster', action='store_true',
                        help='Permit the first init RPC only if no prior initialization intent or cluster ID exists')
    parser.add_argument('--preview-only', action='store_true')
    parser.add_argument('--yes', action='store_true')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,62}', args.stack):
        raise SystemExit('Use a simple local stack name containing letters, numbers, underscores or hyphens')
    state = args.plan_dir.resolve()
    metadata = json.loads((state / 'plan.json').read_text())
    cluster = state / 'cluster.json'
    parsed = json.loads(cluster.read_text())
    public = subprocess.check_output(['ssh-keygen', '-y', '-f', str(args.ssh_private_key.resolve())], text=True)
    if public.split()[:2] != parsed['ssh_authorized_key'].split()[:2]:
        raise SystemExit('SSH private key does not match the pinned plan')
    for program in ('pulumi', 'docker', 'kubectl', args.cilium):
        if not shutil.which(program):
            raise SystemExit(f'Required tool not found: {program}')
    args.cilium = str(Path(shutil.which(args.cilium)).resolve())
    backend = state / 'backend'
    backend.mkdir(mode=0o700, exist_ok=True)
    passphrase = state / 'passphrase'
    if not passphrase.exists():
        fd = os.open(passphrase, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        with os.fdopen(fd, 'w') as output:
            output.write(secrets.token_urlsafe(48) + '\n')
    env = dict(os.environ, PULUMI_BACKEND_URL=backend.as_uri(),
               PULUMI_CONFIG_PASSPHRASE_FILE=str(passphrase))

    def run(command, **kwargs):
        return subprocess.run([str(x) for x in command], cwd=PROJECT, env=env, check=True, **kwargs)

    def pulumi(*command, **kwargs):
        return run(['pulumi', *command, '--stack', args.stack], **kwargs)

    # Stack config lives in the project directory; do not adopt a stack file
    # belonging to another pinned plan or silently alter machine placement.
    config_path = PROJECT / f'Pulumi.{args.stack}.yaml'
    owner = state / 'stack-owner.json'
    identity = {'stack': args.stack, 'configPath': str(config_path), 'flatcarVersion': args.flatcar_version,
                'planSHA256': hashlib.sha256((state / 'plan.json').read_bytes() + cluster.read_bytes()).hexdigest()}
    if config_path.exists() and not owner.exists():
        raise SystemExit('Stack config already exists outside this plan; choose a fresh stack name')
    if not owner.exists():
        run(['pulumi', 'stack', 'init', args.stack, '--non-interactive'])
        values = dict(metadata['pulumiConfig'], flatcarVersion=args.flatcar_version,
                      clusterPath=str(cluster), ignitionDir=str(state / 'output'))
        # JSON values are valid YAML, preserving the salt generated by stack init.
        text = config_path.read_text() + '\nconfig:\n'
        text += '  azure-native:subscriptionId: ' + json.dumps(metadata['subscriptionId']) + '\n'
        text += ''.join('  ' + json.dumps('flatcar-k3s-azure:' + k) + ': ' + json.dumps(v) + '\n' for k,v in values.items())
        config_path.write_text(text)
        config_path.chmod(0o600)
        owner.write_text(json.dumps(identity) + '\n')
        owner.chmod(0o600)
    elif json.loads(owner.read_text()) != identity:
        raise SystemExit('Pinned plan, image, or stack changed; review a deliberate update instead of reselecting a running deployment')
    if not (state / 'pki').exists():
        run([sys.executable, SOURCE / 'generate.py', 'pki', '--config', cluster, '--state-dir', state])
    run([sys.executable, SOURCE / 'generate.py', 'ignition', '--config', cluster, '--state-dir', state])
    plan_path = state / 'deployment-plan.json'
    pulumi('preview', '--refresh', '--diff', '--save-plan=' + str(plan_path))
    if args.preview_only:
        return
    command = ['up', '--refresh', '--plan=' + str(plan_path)]
    if args.yes:
        command.append('--yes')
    pulumi(*command)
    outputs = subprocess.check_output(['pulumi', 'stack', 'output', '--json', '--stack', args.stack], cwd=PROJECT, env=env)
    output_path = state / 'outputs.json'
    output_path.write_bytes(outputs)
    output_path.chmod(0o600)
    command = [sys.executable, PROJECT / 'bootstrap.py', '--state-dir', state, '--cluster', cluster,
               '--outputs', output_path, '--ssh-private-key', args.ssh_private_key.resolve(), '--cilium', args.cilium]
    if args.initialize_new_cluster:
        command.append('--initialize-new-cluster')
    run(command)


if __name__ == '__main__':
    main()
